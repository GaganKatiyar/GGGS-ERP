<#
.SYNOPSIS
    Installs or upgrades GGGS HRMS on a customer's own server.

.DESCRIPTION
    Idempotent by design: running it twice is how an upgrade happens, and a half-finished first
    run should be recoverable by running it again rather than by hand-repairing state.

    Order matters. Database migrations are applied before the new containers start, because the
    expand/contract rule means the new schema is readable by the old code but not the reverse.

.PARAMETER SqlConnectionString
    Connection to the customer's SQL Server. The account needs db_owner on the GGGS databases for
    migrations; the application itself connects with lower privileges.

.PARAMETER Version
    Image tag to install. Defaults to the version in the bundle manifest.

.PARAMETER SkipBackup
    Skips the pre-upgrade backup. Only for a first install, where there is nothing to back up.

.EXAMPLE
    .\install.ps1 -SqlConnectionString "Server=sql01;Database=gggs;Integrated Security=True;Encrypt=True;TrustServerCertificate=True"
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string] $SqlConnectionString,

    [string] $Version,

    [switch] $SkipBackup
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$bundleRoot = $PSScriptRoot
$envFile = Join-Path $bundleRoot 'gggs.env'
$manifestPath = Join-Path $bundleRoot 'bundle.json'

function Write-Step {
    param([string] $Message)
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Test-Prerequisite {
    param([string] $Command, [string] $Hint)

    if (-not (Get-Command $Command -ErrorAction SilentlyContinue)) {
        throw "$Command is required but was not found. $Hint"
    }
}

# --- Preflight ------------------------------------------------------------------------------
# Checked up front rather than failing half way through an upgrade with containers already down.

Write-Step 'Checking prerequisites'
Test-Prerequisite -Command 'docker' -Hint 'Install Docker Engine 24 or later.'

$composeCheck = docker compose version 2>&1
if ($LASTEXITCODE -ne 0) {
    throw "Docker Compose v2 is required. 'docker compose version' reported: $composeCheck"
}

if (-not (Test-Path $manifestPath)) {
    throw "bundle.json was not found next to this script. Run it from inside the release bundle."
}

$manifest = Get-Content $manifestPath -Raw | ConvertFrom-Json
if (-not $Version) { $Version = $manifest.version }

Write-Step "Installing GGGS HRMS $Version"

Write-Step 'Verifying the database is reachable'
try {
    $connection = New-Object System.Data.SqlClient.SqlConnection $SqlConnectionString
    $connection.Open()
    $connection.Close()
}
catch {
    throw "Could not connect to SQL Server with the supplied connection string: $($_.Exception.Message)"
}

# --- Secrets --------------------------------------------------------------------------------
# Generated once and kept, so later runs do not change the connection the containers use.

if (-not (Test-Path $envFile)) {
    Write-Step 'Creating gggs.env with generated credentials'

    @"
# Generated by install.ps1. Treat this file as a secret and include it in your backups.
GGGS_VERSION=$Version
GGGS_SQL_CONNECTION=$SqlConnectionString
GGGS_HTTP_PORT=8080
GGGS_SEQ_PORT=5341
"@ | Set-Content -Path $envFile -Encoding utf8

    Write-Host "    Wrote $envFile" -ForegroundColor DarkGray
}
else {
    Write-Step 'Reusing the existing gggs.env'
    (Get-Content $envFile) -replace '^GGGS_VERSION=.*', "GGGS_VERSION=$Version" |
        Set-Content -Path $envFile -Encoding utf8
}

# --- Backup ---------------------------------------------------------------------------------

if (-not $SkipBackup) {
    Write-Step 'Backing up the database before migrating'

    $backupDirectory = Join-Path $bundleRoot 'backups'
    New-Item -ItemType Directory -Force -Path $backupDirectory | Out-Null
    $backupFile = Join-Path $backupDirectory "gggs-$(Get-Date -Format 'yyyyMMdd-HHmmss').bak"

    $builder = New-Object System.Data.SqlClient.SqlConnectionStringBuilder $SqlConnectionString
    $databaseName = $builder.InitialCatalog

    $connection = New-Object System.Data.SqlClient.SqlConnection $SqlConnectionString
    $connection.Open()
    try {
        $command = $connection.CreateCommand()
        $command.CommandTimeout = 0
        $command.CommandText = "BACKUP DATABASE [$databaseName] TO DISK = @path WITH INIT, COMPRESSION"
        $command.Parameters.AddWithValue('@path', $backupFile) | Out-Null
        $command.ExecuteNonQuery() | Out-Null
        Write-Host "    Backed up to $backupFile (on the SQL Server host)" -ForegroundColor DarkGray
    }
    finally {
        $connection.Close()
    }
}

# --- Images ---------------------------------------------------------------------------------

Write-Step 'Loading application images'
Get-ChildItem -Path (Join-Path $bundleRoot 'images') -Filter '*.tar' -ErrorAction SilentlyContinue |
    ForEach-Object {
        Write-Host "    $($_.Name)" -ForegroundColor DarkGray
        docker load --input $_.FullName | Out-Null
        if ($LASTEXITCODE -ne 0) { throw "Failed to load image $($_.Name)" }
    }

# --- Migrations -----------------------------------------------------------------------------
# Before the new code starts. Migration bundles are self-contained executables, so the customer
# needs no .NET SDK and no EF tooling on the server.

Write-Step 'Applying database migrations'
Get-ChildItem -Path (Join-Path $bundleRoot 'migrations') -Filter '*.exe' -ErrorAction SilentlyContinue |
    Sort-Object Name |
    ForEach-Object {
        Write-Host "    $($_.BaseName)" -ForegroundColor DarkGray
        & $_.FullName --connection $SqlConnectionString
        if ($LASTEXITCODE -ne 0) { throw "Migration $($_.BaseName) failed. The database was not changed beyond this point." }
    }

# --- Start ----------------------------------------------------------------------------------

Write-Step 'Starting services'
docker compose --project-directory $bundleRoot -f (Join-Path $bundleRoot 'compose.onprem.yml') --env-file $envFile up -d --remove-orphans
if ($LASTEXITCODE -ne 0) { throw 'docker compose up failed.' }

# --- Verify ---------------------------------------------------------------------------------
# An install that reports success without checking has only moved the failure to the first user.

Write-Step 'Waiting for the application to report healthy'

$port = (Select-String -Path $envFile -Pattern '^GGGS_HTTP_PORT=(.*)$').Matches.Groups[1].Value
$healthUrl = "http://localhost:$port/health/ready"
$deadline = (Get-Date).AddMinutes(3)
$healthy = $false

while ((Get-Date) -lt $deadline) {
    try {
        $response = Invoke-WebRequest -Uri $healthUrl -UseBasicParsing -TimeoutSec 5
        if ($response.StatusCode -eq 200) { $healthy = $true; break }
    }
    catch {
        Start-Sleep -Seconds 5
    }
}

if (-not $healthy) {
    Write-Host ''
    Write-Host "The application did not become healthy within 3 minutes." -ForegroundColor Red
    Write-Host "Check the logs with: docker compose -f compose.onprem.yml logs api" -ForegroundColor Yellow
    exit 1
}

Write-Host ''
Write-Host "GGGS HRMS $Version is installed and healthy." -ForegroundColor Green
Write-Host "  Application: http://localhost:$port" -ForegroundColor Green
Write-Host "  Logs:        docker compose -f compose.onprem.yml logs -f" -ForegroundColor Green
Write-Host ''
Write-Host 'Back up gggs.env and the gggs-dataprotection volume. Without them the stored' -ForegroundColor Yellow
Write-Host 'integration credentials cannot be decrypted after a rebuild.' -ForegroundColor Yellow
